# Frames are the real ones from captures/pcap/elmsniff_20261103_224924.txt (22:49-22:56,
# engine idling in P) recorded while WJdiag-Pro showed: 751 rpm, coolant 59.5 C, IAT 33 C,
# baro 0.916 bar, boost setpoint 0.938, MAF 486 mg/str, rail 292.3 bar / setpoint 292.6,
# fuel level 38 % (sender 2.13 V), actual fuel 8.23 mg/str, wastegate 85 %, battery 13.81 V.
# Nothing is patched any more.
PATCH = {}
def frames():
    out={}
    for blk,h in BASE.items():
        b=[int(x,16) for x in h.split()]
        for off,v in PATCH.get(blk,{}).items():
            b[off]=(v>>8)&0xFF; b[off+1]=v&0xFF
        out[blk]=b
    return out
F=frames()
# ---- PC sim
p='android-app/sim/wjdiag_sim.py'; s=open(p,encoding='utf-8').read()
a=s.index('_REAL_ECU_HEX = {'); b=s.index('}\n',a)+2
body='_REAL_ECU_HEX = {   # generated by tools/gen_real_ecu.py (real frames 2026-11-02 + WJdiag-Pro screen values)\n'
for blk in sorted(F): body+=' 0x%02X:"%s",\n'%(blk,' '.join('%02X'%x for x in F[blk]))
body+='}\n'
s=s[:a]+body+s[b:]
open(p,'w',encoding='utf-8',newline='\n').write(s); print('sim ok')
# ---- ESP32
p='esp32-emulator/src/elm327_emu.cpp'; raw=open(p,'rb').read().decode('utf-8'); crlf='\r\n' in raw; s=raw.replace('\r\n','\n')
n=0
for blk in sorted(F):
    pat=re.compile(r'\{0x%02X,\s*\d+,\s*\{[^}]*\}\}'%blk)
    rep='{0x%02X,%d,{%s}}'%(blk,len(F[blk]),','.join('0x%02X'%x for x in F[blk]))
    s,k=pat.subn(rep,s,count=1); n+=k
print('esp blocks replaced:',n)
if crlf: s=s.replace('\n','\r\n')
open(p,'wb').write(s.encode('utf-8'))
